begin;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nickname text,
  region text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.activities (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  activity_type text not null check (activity_type in ('outdoor', 'home')),
  category text not null,
  duration_minutes integer check (duration_minutes is null or duration_minutes > 0),
  cost_level integer not null default 0 check (cost_level >= 0),
  cost integer not null default 0 check (cost >= 0),
  weather_type text default 'any',
  companion_types jsonb not null default '[]'::jsonb,
  image_url text,
  is_active boolean not null default true,
  is_fixed_time boolean not null default false,
  fixed_start_time time,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.plans (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  plan_date date not null default current_date,
  title text not null,
  style text,
  region text,
  start_time text,
  end_time text,
  total_cost integer not null default 0 check (total_cost >= 0),
  total_distance_km numeric(8,2) not null default 0,
  total_travel_minutes integer not null default 0,
  companion_type text,
  budget integer check (budget is null or budget >= 0),
  activity_mode text,
  weather_summary text,
  status text not null default 'saved',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.plan_items (
  id bigint generated by default as identity primary key,
  plan_id bigint not null references public.plans(id) on delete cascade,
  activity_id text,
  title text not null,
  activity_type text,
  start_time text,
  end_time text,
  fixed_time boolean not null default false,
  duration_minutes integer check (duration_minutes is null or duration_minutes > 0),
  cost integer not null default 0 check (cost >= 0),
  sort_order integer not null default 0,
  location_name text,
  address text,
  source text,
  latitude double precision,
  longitude double precision,
  travel_minutes integer not null default 0,
  distance_km numeric(8,2) not null default 0,
  transport_mode text not null default 'estimate',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.user_preferences (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  default_region text default '부산',
  budget_level integer default 50000 check (budget_level >= 0),
  companion_type text default 'alone',
  interests jsonb not null default '[]'::jsonb,
  favorite_teams jsonb not null default '[]'::jsonb,
  ott_services jsonb not null default '[]'::jsonb,
  activity_mode text default 'balanced',
  transport_mode text default 'car',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.favorites (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  content_type text not null,
  content_id text not null,
  title text not null,
  image_url text,
  source text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (user_id, content_type, content_id)
);

create table if not exists public.user_sports (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  sport_type text not null,
  league text,
  team_id text,
  team_name text not null,
  created_at timestamptz not null default now(),
  unique (user_id, sport_type, league, team_id)
);

create table if not exists public.user_ott_services (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  provider_id text,
  provider_name text not null,
  created_at timestamptz not null default now(),
  unique (user_id, provider_name)
);

