drop policy if exists "Users manage own profile" on public.profiles;
create policy "Users manage own profile" on public.profiles for all to authenticated
  using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

drop policy if exists "Users manage own plans" on public.plans;
create policy "Users manage own plans" on public.plans for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

drop policy if exists "Users manage own plan items" on public.plan_items;
create policy "Users manage own plan items" on public.plan_items for all to authenticated
  using (exists (select 1 from public.plans p where p.id = plan_items.plan_id and p.user_id = (select auth.uid())))
  with check (exists (select 1 from public.plans p where p.id = plan_items.plan_id and p.user_id = (select auth.uid())));

